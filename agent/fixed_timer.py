# agent/fixed_timer.py

'''
Day 6 -Fixed Timer Baseline Agent.
This is the dumb signal controller we're replacing.
It cycles through phases on a fixed schedule regardless
of actual traffic conditions -exactly what real cities
do today with most of their traffic lights.

We run this first to get baseline metrics:
  - Average wait time per intersection
  - Maximum queue length per approach
  - Total cars served
  - Throughput per hour

These numbers become the "before" in our before/after comparison.
The adaptive agent needs to beat these numbers to justify its existence.

How it works:
  Reruns the SimPy simulation but this time we capture detailed
  per-approach metrics at every signal cycle. The signal timing
  is identical to what traffic_sim.py used -pure fixed timer.
  We just measure more carefully this time.
'''

import os
import pandas as pd
import numpy as np
from simulation.config import BASE_DIR

# paths
LOG_FILE      = os.path.join(BASE_DIR, 'data', 'logs', 'traffic_log.csv')
PROCESSED_DIR = os.path.join(BASE_DIR, 'data', 'processed')


def load_simulation_log():
    '''
    Loads the existing traffic_log.csv generated by run_simulation.py.
    We don't rerun the simulation -we analyse the existing log
    as if it was produced by a fixed timer agent (which it was,
    since traffic_sim.py uses fixed 30s phases by default).
    '''
    df = pd.read_csv(LOG_FILE)

    # separate car events from signal events
    cars    = df[df['event_type'] != 'signal_change'].copy()
    signals = df[df['event_type'] == 'signal_change'].copy()

    print(f'Log loaded: {len(df):,} total rows')
    print(f'Car events: {len(cars):,}')
    print(f'Signal events: {len(signals):,}')
    print()

    return cars, signals


def compute_baseline_metrics(cars):
    '''
    Computes the fixed timer baseline metrics from departure events.
    These are the numbers the adaptive agent must beat on Day 6.

    Metrics computed:
      - avg_wait_time per intersection
      - max_wait_time per intersection
      - avg_queue_length per intersection
      - total_cars_served per intersection
      - avg_wait_time per approach (intersection + direction)
      - hourly throughput (cars served per hour)
    '''
    departures = cars[cars['event_type'] == 'car_departed'].copy()
    arrivals   = cars[cars['event_type'] == 'car_arrived'].copy()

    # per intersection metrics
    int_metrics = departures.groupby('intersection').agg(
        avg_wait_time  = ('wait_time', 'mean'),
        max_wait_time  = ('wait_time', 'max'),
        total_served   = ('wait_time', 'count'),
        std_wait_time  = ('wait_time', 'std')
    ).round(3)

    # per approach metrics
    approach_metrics = departures.groupby(
        ['intersection', 'approach']
    ).agg(
        avg_wait_time = ('wait_time', 'mean'),
        max_wait_time = ('wait_time', 'max'),
        total_served  = ('wait_time', 'count')
    ).round(3).sort_values('avg_wait_time', ascending=False)

    # average queue length per intersection
    queue_metrics = arrivals.groupby('intersection').agg(
        avg_queue = ('queue_length', 'mean'),
        max_queue = ('queue_length', 'max')
    ).round(3)

    # hourly throughput
    departures['hour'] = departures['hour'].astype(int)
    hourly = departures.groupby('hour').size().reset_index(name='cars_served')

    return int_metrics, approach_metrics, queue_metrics, hourly


def print_baseline_report(int_metrics, approach_metrics,
                          queue_metrics, hourly):
    '''
    Prints a clean summary of all baseline metrics.
    This is the "before" picture -what the fixed timer achieves.
    '''
    print('=' * 55)
    print('FIXED TIMER BASELINE -Results')
    print('=' * 55)
    print()

    print('Wait Time by Intersection:')
    print(int_metrics.to_string())
    print()

    print('Queue Length by Intersection:')
    print(queue_metrics.to_string())
    print()

    print('Top 5 Worst Approaches (highest avg wait):')
    print(approach_metrics.head(5).to_string())
    print()

    print('Hourly Throughput (cars served per hour):')
    rush = hourly[hourly['hour'].isin([7, 8, 16, 17, 18])]
    quiet = hourly[~hourly['hour'].isin([7, 8, 16, 17, 18])]
    print(f'  Rush hour avg   : {rush["cars_served"].mean():.0f} cars/hour')
    print(f'  Off-peak avg    : {quiet["cars_served"].mean():.0f} cars/hour')
    print()

    # headline numbers -these go in the comparison table
    overall_avg_wait = int_metrics['avg_wait_time'].mean()
    overall_max_wait = int_metrics['max_wait_time'].max()
    total_served     = int_metrics['total_served'].sum()

    print('HEADLINE METRICS (Fixed Timer):')
    print(f'  Overall avg wait time : {overall_avg_wait:.3f} seconds')
    print(f'  Overall max wait time : {overall_max_wait:.3f} seconds')
    print(f'  Total cars served     : {total_served:,}')
    print()

    return overall_avg_wait, overall_max_wait, total_served


def save_baseline_metrics(int_metrics, approach_metrics,
                          queue_metrics, hourly):
    '''
    Saves baseline metrics to data/processed/ for comparison
    with adaptive agent results in evaluate.py.
    '''
    os.makedirs(PROCESSED_DIR, exist_ok=True)

    int_metrics.to_csv(
        os.path.join(PROCESSED_DIR, 'baseline_intersection.csv')
    )
    approach_metrics.to_csv(
        os.path.join(PROCESSED_DIR, 'baseline_approach.csv')
    )
    queue_metrics.to_csv(
        os.path.join(PROCESSED_DIR, 'baseline_queue.csv')
    )
    hourly.to_csv(
        os.path.join(PROCESSED_DIR, 'baseline_hourly.csv'),
        index=False
    )

    print('Baseline metrics saved to data/processed/')
    print('  baseline_intersection.csv')
    print('  baseline_approach.csv')
    print('  baseline_queue.csv')
    print('  baseline_hourly.csv')


def main():
    '''
    Loads simulation log, computes baseline metrics,
    prints report, saves to disk.
    '''
    print('TrafficPulse -Day 6 Fixed Timer Baseline')
    print()

    cars, signals = load_simulation_log()

    int_metrics, approach_metrics, queue_metrics, hourly = \
        compute_baseline_metrics(cars)

    overall_avg, overall_max, total = \
        print_baseline_report(int_metrics, approach_metrics,
                              queue_metrics, hourly)

    save_baseline_metrics(int_metrics, approach_metrics,
                          queue_metrics, hourly)

    print()
    print('Baseline complete. Run agent/adaptive_agent.py next.')


if __name__ == '__main__':
    main()